package Session3;

public class Graduated {
     public static void main(String[] args) {
        int score = 80;

        if (score >= 90) {
            System.out.println("You get Grade: A");
        } else if (score >= 80) {
            System.out.println("You get Grade: B");
        } else if (score >= 70) {
            System.out.println("You get Grade: C");
        } else {
            System.out.println("You get Grade: D");
        }
  
    }
}
